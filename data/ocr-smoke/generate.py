"""Generate wholly synthetic smoke images; no fonts/models/documents are copied."""

import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, __version__ as pillow_version


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--font", type=Path, required=True, help="Local Unicode TTF; not redistributed")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    image = Image.new("RGB", (1600, 1050), "white")
    draw = ImageDraw.Draw(image)
    lines = [
        ("HÓA ĐƠN BÁN HÀNG", 62),
        ("DỮ LIỆU TỔNG HỢP - KHÔNG CÓ GIÁ TRỊ THANH TOÁN", 30),
        ("Số hóa đơn: HD-0000123", 44),
        ("Ngày lập: 03/04/2026", 44),
        ("Người bán: Cửa hàng Mây Việt (GIẢ LẬP)", 44),
        ("Tổng tiền: 125.000 VND", 44),
        ("Đơn vị tiền tệ: VND", 44),
    ]
    y = 80
    for text, size in lines:
        draw.text((80, y), text, font=ImageFont.truetype(str(args.font), size), fill="black")
        y += 110
    images = [("invoice_vi.png", image, "image/png"),
              ("invoice_vi.jpg", image, "image/jpeg"),
              ("blank.png", Image.new("RGB", (800, 400), "white"), "image/png")]
    manifest = {
        "version": "ocr-smoke-1", "synthetic": True,
        "source": "Original AI-02 fixture text/layout generated by generate.py; no real invoice or personal data",
        "license": "CC0-1.0 for the original fixture text/layout and generated sample images",
        "font": {"file_name": args.font.name, "sha256": hashlib.sha256(args.font.read_bytes()).hexdigest(),
                 "redistributed": False},
        "pillow_version": pillow_version, "images": [],
    }
    for name, canvas, media in images:
        if media == "image/jpeg":
            canvas.save(root / name, quality=95, dpi=(300, 300))
        else:
            canvas.save(root / name, dpi=(300, 300))
        manifest["images"].append({
            "id": Path(name).stem + ("-jpeg" if media == "image/jpeg" else ""),
            "file": name, "media_type": media, "width": canvas.width, "height": canvas.height,
            "sha256": hashlib.sha256((root / name).read_bytes()).hexdigest(),
            "source_locale": "vi-VN", "expected_text": "" if name == "blank.png" else "\n".join(text for text, _ in lines),
        })
    (root / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
